-- La tabla de administradores no permite autoasignarse el rol desde la web.

create table if not exists public.patoton_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.patoton_donations (
  id bigint generated by default as identity primary key,
  donation_type text not null,
  donor_name text not null,
  contact text,
  message text,
  status text not null default 'pending' check(status in ('pending','received')),
  created_at timestamptz not null default now()
);
create table if not exists public.patoton_volunteers (
  id bigint generated by default as identity primary key,
  full_name text not null,
  contact text,
  availability text,
  status text not null default 'pending' check(status in ('pending','confirmed')),
  created_at timestamptz not null default now()
);
create table if not exists public.patoton_updates (
  id bigint generated by default as identity primary key,
  title text not null,
  body text not null,
  is_public boolean not null default true,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.patoton_admins enable row level security;
alter table public.patoton_donations enable row level security;
alter table public.patoton_volunteers enable row level security;
alter table public.patoton_updates enable row level security;

create or replace function public.patoton_is_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.patoton_admins where user_id=auth.uid()); $$;
grant execute on function public.patoton_is_admin() to authenticated;

grant select,insert,update,delete on public.patoton_donations to anon,authenticated;
grant select,insert,update,delete on public.patoton_volunteers to anon,authenticated;
grant select,insert,update,delete on public.patoton_updates to anon,authenticated;
grant select on public.patoton_admins to authenticated;
grant usage,select on all sequences in schema public to anon,authenticated;

drop policy if exists "Public can submit donation proposals" on public.patoton_donations;
create policy "Public can submit donation proposals" on public.patoton_donations
for insert to anon,authenticated with check(status='pending');
drop policy if exists "Admins manage donation proposals" on public.patoton_donations;
create policy "Admins manage donation proposals" on public.patoton_donations
for all to authenticated using(public.patoton_is_admin()) with check(public.patoton_is_admin());

drop policy if exists "Public can register volunteer interest" on public.patoton_volunteers;
create policy "Public can register volunteer interest" on public.patoton_volunteers
for insert to anon,authenticated with check(status='pending');
drop policy if exists "Admins manage volunteers" on public.patoton_volunteers;
create policy "Admins manage volunteers" on public.patoton_volunteers
for all to authenticated using(public.patoton_is_admin()) with check(public.patoton_is_admin());

drop policy if exists "Public can read public updates" on public.patoton_updates;
create policy "Public can read public updates" on public.patoton_updates
for select to anon,authenticated using(is_public=true);
drop policy if exists "Admins manage updates" on public.patoton_updates;
create policy "Admins manage updates" on public.patoton_updates
for all to authenticated using(public.patoton_is_admin()) with check(public.patoton_is_admin());

drop policy if exists "Admins can read own admin record" on public.patoton_admins;
create policy "Admins can read own admin record" on public.patoton_admins
for select to authenticated using(user_id=auth.uid());

