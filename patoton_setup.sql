-- Totales públicos editables desde el panel administrador.
create table if not exists public.patoton_raised_totals (
  id integer primary key default 1 check (id=1),
  money_mxn numeric(12,2) not null default 0 check (money_mxn>=0),
  toys integer not null default 0 check (toys>=0),
  clothes integer not null default 0 check (clothes>=0),
  food integer not null default 0 check (food>=0),
  updated_at timestamptz not null default now()
);
insert into public.patoton_raised_totals(id) values(1) on conflict(id) do nothing;
alter table public.patoton_raised_totals enable row level security;
grant select on public.patoton_raised_totals to anon, authenticated;
grant update on public.patoton_raised_totals to authenticated;
drop policy if exists "Public can read raised totals" on public.patoton_raised_totals;
create policy "Public can read raised totals" on public.patoton_raised_totals
for select to anon,authenticated using(true);
drop policy if exists "Admins update raised totals" on public.patoton_raised_totals;
create policy "Admins update raised totals" on public.patoton_raised_totals
for update to authenticated using(public.patoton_is_admin()) with check(public.patoton_is_admin());

-- Videos publicados en PATOTÓN TV. Los visitantes solo pueden leer publicaciones públicas.
create table if not exists public.patoton_videos (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  source_type text not null check(source_type in ('youtube','upload')),
  youtube_url text,
  storage_path text,
  is_featured boolean not null default false,
  is_public boolean not null default true,
  created_at timestamptz not null default now(),
  created_by uuid references auth.users(id)
);
alter table public.patoton_videos enable row level security;
grant select,insert,update,delete on public.patoton_videos to anon,authenticated;
grant usage,select on all sequences in schema public to authenticated;
drop policy if exists "Public read published PATOTON TV videos" on public.patoton_videos;
create policy "Public read published PATOTON TV videos" on public.patoton_videos
for select to anon,authenticated using(is_public=true);
drop policy if exists "Admins manage PATOTON TV videos" on public.patoton_videos;
create policy "Admins manage PATOTON TV videos" on public.patoton_videos
for all to authenticated using(public.patoton_is_admin()) with check(public.patoton_is_admin());

-- Storage bucket para videos subidos por administradores.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('patoton-tv','patoton-tv',true,52428800,array['video/mp4','video/webm','video/quicktime'])
on conflict(id) do update set public=true,file_size_limit=52428800,allowed_mime_types=array['video/mp4','video/webm','video/quicktime'];

drop policy if exists "Public can view PATOTON TV files" on storage.objects;
create policy "Public can view PATOTON TV files" on storage.objects
for select to anon,authenticated using(bucket_id='patoton-tv');
drop policy if exists "Admins upload PATOTON TV files" on storage.objects;
create policy "Admins upload PATOTON TV files" on storage.objects
for insert to authenticated with check(bucket_id='patoton-tv' and public.patoton_is_admin());
drop policy if exists "Admins update PATOTON TV files" on storage.objects;
create policy "Admins update PATOTON TV files" on storage.objects
for update to authenticated using(bucket_id='patoton-tv' and public.patoton_is_admin()) with check(bucket_id='patoton-tv' and public.patoton_is_admin());
drop policy if exists "Admins delete PATOTON TV files" on storage.objects;
create policy "Admins delete PATOTON TV files" on storage.objects
for delete to authenticated using(bucket_id='patoton-tv' and public.patoton_is_admin());

-- Activar Realtime para totales y videos públicos.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='patoton_raised_totals'
  ) then alter publication supabase_realtime add table public.patoton_raised_totals; end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='patoton_videos'
  ) then alter publication supabase_realtime add table public.patoton_videos; end if;
end $$;
